/**
 * usageEvents.js — what actually happened, without recording who did it.
 *
 * TRL 9 means "proven in an operational environment", which cannot be claimed
 * from a demo script: it needs a record of real sessions. Nothing in this
 * codebase measured usage before, so there was no evidence trail by
 * construction.
 *
 * Two design choices, both to keep the privacy surface as small as possible:
 *
 * 1. RECORDED SERVER-SIDE. The server already sees every milestone request, so
 *    the frontend sends nothing extra and there is no second copy of the mapping
 *    to drift. Instrumenting pages would have been six edits and six chances to
 *    disagree about what a "session" is.
 *
 * 2. OPT-IN, AND IDENTITY-FREE. Off unless KISAN_TELEMETRY=on. A record holds
 *    the milestone, the coarse role, the district, the locale and a random
 *    install id generated by the browser — never a uid, name, phone, price or
 *    free text. The install id exists only so "5 devices" can be counted; it is
 *    not linked to any account and is regenerated if storage is cleared.
 *
 * What this is NOT: an analytics product. It answers exactly the questions a
 * pilot report needs — how many sessions, decisions, lots, offers, settlements
 * and grievances, and on how many distinct devices — and nothing else.
 */

// Method + path prefix → milestone name. Only these are ever recorded; a
// request that is not a milestone leaves no trace at all.
const MILESTONES = [
  { method: 'POST', pattern: /^\/api\/auth\/demo-login/, event: 'session_started' },
  { method: 'GET', pattern: /^\/api\/market\/net-realization/, event: 'decision_run' },
  { method: 'POST', pattern: /^\/api\/grade-assessment\/?$/, event: 'grade_submitted' },
  { method: 'POST', pattern: /^\/api\/lots\/?$/, event: 'lot_created' },
  { method: 'POST', pattern: /^\/api\/offers\/?$/, event: 'offer_sent' },
  { method: 'POST', pattern: /^\/api\/offers\/[^/]+\/accept$/, event: 'offer_accepted' },
  { method: 'POST', pattern: /^\/api\/payments\/[^/]+\/simulate-release$/, event: 'payment_released' },
  { method: 'POST', pattern: /^\/api\/payments\/[^/]+\/simulate-failure$/, event: 'payment_failed' },
  { method: 'POST', pattern: /^\/api\/grievances\/?$/, event: 'grievance_raised' },
  { method: 'POST', pattern: /^\/api\/fpo\/pool\/?$/, event: 'pool_joined' },
];

const ALLOWED_EVENTS = MILESTONES.map((m) => m.event);

/** Milestone name for a request, or null when it is not one. */
function milestoneFor(method, originalUrl) {
  if (!method || !originalUrl) return null;
  const path = String(originalUrl).split('?')[0];
  const upper = String(method).toUpperCase();
  const hit = MILESTONES.find((m) => m.method === upper && m.pattern.test(path));
  return hit ? hit.event : null;
}

/**
 * Identity for the session milestone, which has no token to decode — it is the
 * request asking for one.
 *
 * Demo-login runs the requested role through the server's own allow-list
 * (normalizeRole) and mints the result into the token, so the same normalised
 * value is what the session actually carries. Reading it here is therefore not a
 * client-supplied guess, and it is the difference between "farmer sessions" —
 * the headline pilot number — being answerable and every session recording
 * `anonymous`.
 *
 * Imported rather than re-listed so the allow-list has one home; a duplicate
 * copy here could silently disagree with the token the server issues.
 */
const { normalizeRole, DEMO_PROFILES } = require('../services/demoAuth');

function sessionIdentityFromBody(req) {
  const body = (req && req.body) || {};
  const role = normalizeRole(body.role);
  const profile = DEMO_PROFILES[role] || {};
  return { role, district: body.district || profile.district || null };
}

/** Off unless explicitly enabled — no silent collection, ever. */
function isTelemetryEnabled() {
  const flag = String(process.env.KISAN_TELEMETRY || '').toLowerCase();
  return flag === 'on' || flag === '1' || flag === 'true';
}

/**
 * The only fields a record may carry. A whitelist rather than a blacklist: a
 * future change that tries to store something new has to be named here first.
 */
function buildRecord({ event, user, locale, installId }) {
  if (!ALLOWED_EVENTS.includes(event)) return null;
  const record = {
    event,
    at: new Date(),
    role: (user && user.role) ? String(user.role).slice(0, 20) : 'anonymous',
    district: (user && user.district) ? String(user.district).slice(0, 40) : null,
    locale: locale ? String(locale).slice(0, 12) : null,
    installId: installId ? String(installId).replace(/[^a-zA-Z0-9-]/g, '').slice(0, 40) : null,
  };
  return record;
}

module.exports = { MILESTONES, ALLOWED_EVENTS, milestoneFor, isTelemetryEnabled, buildRecord, sessionIdentityFromBody };
